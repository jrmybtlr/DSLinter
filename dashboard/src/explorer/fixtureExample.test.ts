import { describe, expect, it } from "vitest";
import type { CatalogComponent } from "../types/report";
import {
  adapterKey,
  fixtureAdapterExample,
  fixtureEntry,
} from "./fixtureExample";
import {
  propDiagnostics,
  summarizeProps,
  summarizePropValue,
} from "./previewMessages";

function component(
  preview: Partial<CatalogComponent["preview"]> = {},
): CatalogComponent {
  return {
    id: "app/components/forecast/ForecastHours.vue#default",
    name: "ForecastHours",
    framework: "vue",
    preview: {
      id: "ForecastHours",
      rel_path: "app/components/forecast/ForecastHours.vue",
      export_name: "default",
      declared_props: ["hours", "previewHour", "onSelect"],
      declared_prop_kinds: {
        hours: "object",
        previewHour: "number",
        onSelect: "function",
      },
      declared_prop_optional: {
        hours: false,
        previewHour: true,
        onSelect: true,
      },
      declared_prop_type_labels: { hours: "HourlySnapshot[]" },
      ...preview,
    },
    usages: [],
    dependencies: [],
    bindings: {},
  } as CatalogComponent;
}

describe("fixture examples", () => {
  it("writes sample props as an editable fixture entry", () => {
    const example = fixtureAdapterExample(
      component({
        sample_props: {
          hours: [{ time: "2025-06-02T09:00:00", temperature: 18 }],
        },
      }),
    );
    expect(example)
      .toBe(`import type { PreviewAdapter } from "dslinter/preview";

export default {
  fixtures: {
    // Sample data generated by DSLinter. Edit it to match real data.
    ForecastHours: {
      hours: [
        {
          time: "2025-06-02T09:00:00",
          temperature: 18,
        },
      ],
    },
  },
} satisfies PreviewAdapter;`);
  });

  it("marks required props without samples as TODO placeholders", () => {
    expect(fixtureEntry(component(), "ForecastHours")).toBe(
      "ForecastHours: {\n  hours: [], // TODO: required HourlySnapshot[]\n}",
    );
  });

  it("escapes keys and string values instead of emitting code", () => {
    const entry = fixtureEntry(
      component({
        declared_props: ["data-id"],
        declared_prop_optional: { "data-id": false },
        sample_props: { "data-id": '"; alert(1); "' },
      }),
      "X",
    );
    expect(entry).toContain('"data-id": "\\"; alert(1); \\""');
  });

  it("uses the canonical id when names are shared", () => {
    const item = component();
    expect(adapterKey(item, [item, { ...item, id: "other#default" }])).toBe(
      JSON.stringify(item.id),
    );
    expect(adapterKey(item, [item])).toBe("ForecastHours");
  });
});

describe("prop diagnostics", () => {
  it("summarizes values without cloning functions", () => {
    expect(summarizePropValue(undefined)).toBe("undefined");
    expect(summarizePropValue([])).toBe("[] (empty)");
    expect(summarizePropValue([{ a: 1 }, { a: 2 }])).toBe(
      '2 items: [{"a":1},{"a":2}]',
    );
    expect(summarizePropValue(() => 1)).toBe("function");
    expect(summarizePropValue("x".repeat(200))).toHaveLength(80);
    expect(summarizeProps({ hours: [], "slot:default": "x" })).toEqual({
      hours: "[] (empty)",
    });
  });

  it("lists every declared prop and flags missing required data first", () => {
    expect(propDiagnostics(component(), { previewHour: "null" })).toEqual([
      { name: "hours", value: "undefined", required: true, problem: true },
      { name: "previewHour", value: "null", required: false, problem: false },
    ]);
    expect(propDiagnostics(component(), undefined)).toEqual([]);
  });
});
