import type { CatalogComponent } from "../types/report";

const SKIPPED_KINDS = new Set(["function", "node", "icon"]);
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

function key(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

/** Prints JSON-like data as a readable object literal; never emits code from the values. */
function literal(value: unknown, depth: number): string {
  const pad = "  ".repeat(depth + 1);
  const close = "  ".repeat(depth);
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number")
    return Number.isFinite(value) ? String(value) : "0";
  if (typeof value === "boolean") return String(value);
  if (Array.isArray(value)) {
    if (!value.length) return "[]";
    const items = value.map((item) => literal(item, depth + 1));
    const inline = `[${items.join(", ")}]`;
    if (inline.length <= 60 && !inline.includes("\n")) return inline;
    return `[\n${items.map((item) => pad + item).join(",\n")},\n${close}]`;
  }
  if (typeof value === "object") {
    const entries = Object.entries(value as Record<string, unknown>).filter(
      ([, item]) => item !== undefined && typeof item !== "function",
    );
    if (!entries.length) return "{}";
    return `{\n${entries.map(([name, item]) => `${pad}${key(name)}: ${literal(item, depth + 1)}`).join(",\n")},\n${close}}`;
  }
  return "undefined";
}

function placeholder(
  component: CatalogComponent,
  name: string,
): string | undefined {
  const kind = component.preview.declared_prop_kinds?.[name];
  const label = component.preview.declared_prop_type_labels?.[name] || "";
  if (kind === "stringArray" || kind === "numberArray") return "[]";
  if (kind === "object") return /\[\]$|^Array</.test(label) ? "[]" : "{}";
  if (kind === "string") return '""';
  if (kind === "number") return "0";
  if (kind === "boolean") return "false";
  return undefined;
}

/** Key used in adapter maps: the name unless another catalog component shares it. */
export function adapterKey(
  component: CatalogComponent,
  catalog: CatalogComponent[] = [],
): string {
  const shared =
    catalog.filter((item) => item.name === component.name).length > 1;
  return shared || !IDENTIFIER.test(component.name)
    ? JSON.stringify(component.id)
    : component.name;
}

/**
 * The fixture entry DSLinter would write: its sample props, plus a TODO placeholder for each
 * required prop it could not sample, so the gap is visible where the user edits.
 */
export function fixtureEntry(
  component: CatalogComponent,
  entryKey: string,
): string | undefined {
  const spec = component.preview;
  const samples = spec.sample_props || {};
  const lines: string[] = [];
  for (const name of spec.declared_props) {
    if (
      /^on[A-Z]/.test(name) ||
      SKIPPED_KINDS.has(spec.declared_prop_kinds?.[name] || "")
    )
      continue;
    const value = samples[name];
    if (value !== undefined && typeof value !== "function") {
      lines.push(`  ${key(name)}: ${literal(value, 1)},`);
      continue;
    }
    if (spec.declared_prop_optional?.[name] !== false) continue;
    const fallback = placeholder(component, name);
    if (fallback)
      lines.push(
        `  ${key(name)}: ${fallback}, // TODO: required${spec.declared_prop_type_labels?.[name] ? ` ${spec.declared_prop_type_labels[name]}` : ""}`,
      );
  }
  for (const [name, value] of Object.entries(samples))
    if (
      !spec.declared_props.includes(name) &&
      value !== undefined &&
      typeof value !== "function"
    )
      lines.push(`  ${key(name)}: ${literal(value, 1)},`);
  if (!lines.length) return;
  return `${entryKey}: {\n${lines.join("\n")}\n}`;
}

function indent(text: string, by: string): string {
  return text
    .split("\n")
    .map((line) => (line ? by + line : line))
    .join("\n");
}

export const FIXTURE_COMMENT =
  "// Sample data generated by DSLinter. Edit it to match real data.";

export function fixtureAdapterExample(
  component: CatalogComponent,
  catalog: CatalogComponent[] = [],
  format: "tsx" | "js" = "tsx",
): string | undefined {
  const entry = fixtureEntry(component, adapterKey(component, catalog));
  if (!entry) return;
  const body = [
    "  fixtures: {",
    indent(FIXTURE_COMMENT, "    "),
    `${indent(entry, "    ")},`,
    "  },",
  ];
  return format === "js"
    ? ["export default {", ...body, "};"].join("\n")
    : [
        'import type { PreviewAdapter } from "dslinter/preview";',
        "",
        "export default {",
        ...body,
        "} satisfies PreviewAdapter;",
      ].join("\n");
}
